"""Turn the never-populated ``Product`` stub into a real ``Species`` table.

Written by hand rather than autogenerated so it is a *rename*: ``Lot.species`` has always been a
foreign key to this table, and the handful of rows anyone did create keep their primary keys
instead of being dropped and rebuilt underneath those lots.

Also switches the scientific name on by default for auctions that already exist -- the field is
new, so no lot has a species yet and no label changes shape until a seller picks one, but a club
that never visits the label settings should still get the behaviour the default promises.
"""

