def enable_scientific_name_on_labels(apps, schema_editor):
    """Append ``scientific_name`` to every auction's label field list.

    A no-op on the printed page until a lot actually has a species, and an admin who doesn't want
    it can untick it in the auction's label settings like any other field.
    """
    Auction = apps.get_model("auctions", "Auction")
    for auction in Auction.objects.exclude(label_print_fields__contains="scientific_name").iterator():
        fields = [field for field in (auction.label_print_fields or "").split(",") if field]
        if not fields:
            continue
        # Right after the lot name, matching where it prints.
        position = fields.index("lot_name") + 1 if "lot_name" in fields else len(fields)
        fields.insert(position, "scientific_name")
        auction.label_print_fields = ",".join(fields)
        auction.save(update_fields=["label_print_fields"])


def remove_scientific_name_from_labels(apps, schema_editor):
    Auction = apps.get_model("auctions", "Auction")
    for auction in Auction.objects.filter(label_print_fields__contains="scientific_name").iterator():
        fields = [field for field in (auction.label_print_fields or "").split(",") if field != "scientific_name"]
        auction.label_print_fields = ",".join(fields)
        auction.save(update_fields=["label_print_fields"])


